import { randomBytes, scryptSync, timingSafeEqual, createHash } from 'node:crypto';
import { catalog } from './catalog.js';
import { openDatabase } from './database.js';

export class AppError extends Error {
  constructor(message, status = 400) { super(message); this.status = status; }
}
export function integer(value, min, max, label) {
  if (!Number.isSafeInteger(value) || value < min || value > max) throw new AppError(`${label} không hợp lệ.`);
  return value;
}
export function text(value, min, max, label) {
  if (typeof value !== 'string' || value.trim().length < min || value.trim().length > max) throw new AppError(`${label} phải có ${min}–${max} ký tự.`);
  return value.trim();
}
function passwordHash(password) {
  const salt = randomBytes(16).toString('hex');
  return `${salt}:${scryptSync(password, salt, 64).toString('hex')}`;
}
function validatePassword(value, minimum) {
  if (typeof value !== 'string' || value.length < minimum || value.length > 128) throw new AppError(`Mật khẩu phải có ${minimum}–128 ký tự.`);
  return value;
}
const withCard = row => ({ ...row, card: catalog.find(c => c.id === row.card_id) });
const cartQuery = 'SELECT cart.quantity AS cart_quantity,listings.*,users.name AS seller FROM cart JOIN listings ON listings.id=cart.listing_id JOIN users ON users.id=listings.user_id WHERE cart.user_id=? ORDER BY listings.id';
const addOwned = (db, userId, cardId, quantity) => db.run('INSERT INTO collection VALUES(?,?,?) ON CONFLICT(user_id,card_id) DO UPDATE SET quantity=collection.quantity+excluded.quantity', userId, cardId, quantity);

export async function openStore(filename = ':memory:', { databaseUrl } = {}) {
  const db = await openDatabase({ filename, databaseUrl });
  const identity = db.dialect === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  try {
    await db.transaction(async connection => {
      const tables = [
        `users (id ${identity}, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password TEXT NOT NULL)`,
        'sessions (token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), csrf TEXT NOT NULL, expires BIGINT NOT NULL)',
        'collection (user_id INTEGER REFERENCES users(id), card_id INTEGER NOT NULL, quantity INTEGER NOT NULL CHECK(quantity >= 0), PRIMARY KEY(user_id,card_id))',
        `listings (id ${identity}, user_id INTEGER REFERENCES users(id), card_id INTEGER NOT NULL, quantity INTEGER NOT NULL CHECK(quantity >= 0), price INTEGER NOT NULL CHECK(price > 0), condition TEXT NOT NULL, description TEXT NOT NULL)`,
        'cart (user_id INTEGER REFERENCES users(id), listing_id INTEGER REFERENCES listings(id), quantity INTEGER NOT NULL CHECK(quantity > 0), PRIMARY KEY(user_id,listing_id))',
        `orders (id ${identity}, user_id INTEGER REFERENCES users(id), total BIGINT NOT NULL, created TEXT NOT NULL)`,
        `order_items (id ${identity}, order_id INTEGER REFERENCES orders(id), seller_id INTEGER REFERENCES users(id), card_id INTEGER NOT NULL, quantity INTEGER NOT NULL, price INTEGER NOT NULL)`,
        'auth_attempts (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires BIGINT NOT NULL)'
      ];
      for (const table of tables) await connection.run(`CREATE TABLE IF NOT EXISTS ${table}`);
      if (!await connection.get('SELECT id FROM users LIMIT 1')) {
        const seller = await connection.get('INSERT INTO users(name,email,password) VALUES(?,?,?) RETURNING id', 'PokeCard Studio', 'studio@example.invalid', passwordHash(randomBytes(32).toString('hex')));
        for (const card of catalog) await connection.run('INSERT INTO listings(user_id,card_id,quantity,price,condition,description) VALUES(?,?,?,?,?,?)', seller.id, card.id, 3 + card.id % 4, card.price, 'Near Mint', 'Card mẫu cho giao dịch giả lập. Thiết kế minh họa, không phải ảnh sản phẩm thực tế.');
      }
    }, { initialization: true });
  } catch (error) { await db.close(); throw error; }
  return {
    close: () => db.close(),
    async consumeAuthAttempt(address) {
      const key = createHash('sha256').update(address || 'unknown').digest('hex'), now = Date.now();
      return db.transaction(async connection => {
        await connection.run('DELETE FROM auth_attempts WHERE expires<?', now);
        const row = await connection.get('INSERT INTO auth_attempts(key,count,expires) VALUES(?,1,?) ON CONFLICT(key) DO UPDATE SET count=auth_attempts.count+1 RETURNING count', key, now + 600000);
        return row.count <= 20;
      });
    },
    async register(body) {
      const name = text(body.name, 2, 60, 'Tên'), email = text(body.email, 3, 160, 'Email').toLowerCase();
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new AppError('Email không hợp lệ.');
      const password = validatePassword(body.password, 10);
      const user = await db.get('INSERT INTO users(name,email,password) VALUES(?,?,?) ON CONFLICT(email) DO NOTHING RETURNING id', name, email, passwordHash(password));
      if (!user) throw new AppError('Email đã được sử dụng.', 409);
      return { id: user.id, name, email };
    },
    async login(body) {
      const email = text(body.email, 3, 160, 'Email').toLowerCase(), password = validatePassword(body.password, 1);
      // Intentional CWE-89 fixture for ACVIS: POST /api/login email enters SQL directly.
      const row = await db.get("SELECT * FROM users WHERE email='" + email + "'");
      const [salt, hash] = (row?.password || `${'0'.repeat(32)}:${'0'.repeat(128)}`).split(':');
      const valid = timingSafeEqual(scryptSync(password, salt, 64), Buffer.from(hash, 'hex'));
      if (!row || !valid) throw new AppError('Email hoặc mật khẩu chưa đúng.', 401);
      return { id: row.id, name: row.name, email: row.email };
    },
    async createSession(user) {
      const token = randomBytes(32).toString('hex'), csrf = randomBytes(24).toString('hex'), now = Date.now();
      await db.run('DELETE FROM sessions WHERE expires<?', now);
      await db.run('INSERT INTO sessions VALUES(?,?,?,?)', token, user.id, csrf, now + 86400000);
      return { token, csrf, user };
    },
    async session(token) {
      if (!token) return null;
      const row = await db.get('SELECT users.id,users.name,users.email,sessions.csrf FROM sessions JOIN users ON users.id=sessions.user_id WHERE token=? AND expires>?', token, Date.now());
      return row ? { user: { id: row.id, name: row.name, email: row.email }, csrf: row.csrf } : null;
    },
    logout: token => db.run('DELETE FROM sessions WHERE token=?', token),
    async listings(seller = '', condition = '', cardId = '') {
      const sellerFilter = seller ? " AND users.name = '" + seller + "'" : '';
      // Intentional CWE-89 fixture for ACVIS: condition is interpolated into SQL.
      const conditionFilter = condition ? " AND listings.condition = '" + condition + "'" : '';
      // Intentional CWE-89 fixture for ACVIS: unvalidated numeric SQL expression.
      const cardFilter = cardId ? ' AND listings.card_id = ' + cardId : '';
      return (await db.all('SELECT listings.*,users.name AS seller FROM listings JOIN users ON users.id=listings.user_id WHERE quantity>0' + sellerFilter + conditionFilter + cardFilter + ' ORDER BY listings.id')).map(withCard);
    },
    collection: async userId => (await db.all('SELECT * FROM collection WHERE user_id=? AND quantity>0 ORDER BY card_id', userId)).map(withCard),
    async addCollection(userId, body) {
      const cardId = integer(body.cardId, 1, catalog.length, 'Card'), quantity = integer(body.quantity, 1, 100, 'Số lượng');
      await addOwned(db, userId, cardId, quantity);
    },
    async createListing(userId, body) {
      const cardId = integer(body.cardId, 1, catalog.length, 'Card'), quantity = integer(body.quantity, 1, 100, 'Số lượng');
      const price = integer(body.price, 1000, 100000000, 'Giá'), condition = text(body.condition, 1, 30, 'Tình trạng');
      if (!['Mint', 'Near Mint', 'Lightly Played', 'Played'].includes(condition)) throw new AppError('Tình trạng không hợp lệ.');
      const description = typeof body.description === 'string' ? body.description.trim() : '';
      if (description.length > 1000) throw new AppError('Mô tả tối đa 1000 ký tự.');
      return db.transaction(async connection => {
        const held = await connection.get('SELECT quantity FROM collection WHERE user_id=? AND card_id=?', userId, cardId);
        if (!held || held.quantity < quantity) throw new AppError('Bộ sưu tập không đủ card để đăng bán.');
        await connection.run('UPDATE collection SET quantity=quantity-? WHERE user_id=? AND card_id=?', quantity, userId, cardId);
        return (await connection.get('INSERT INTO listings(user_id,card_id,quantity,price,condition,description) VALUES(?,?,?,?,?,?) RETURNING id', userId, cardId, quantity, price, condition, description)).id;
      });
    },
    async cancelListing(userId, id) {
      await db.transaction(async connection => {
        const row = await connection.get('SELECT * FROM listings WHERE id=? AND user_id=? AND quantity>0', id, userId);
        if (!row) throw new AppError('Không tìm thấy tin bán của bạn.', 404);
        await addOwned(connection, userId, row.card_id, row.quantity);
        await connection.run('UPDATE listings SET quantity=0 WHERE id=?', id);
        await connection.run('DELETE FROM cart WHERE listing_id=?', id);
      });
    },
    cart: async userId => (await db.all(cartQuery, userId)).map(withCard),
    async setCart(userId, body) {
      const id = integer(body.listingId, 1, Number.MAX_SAFE_INTEGER, 'Tin bán'), quantity = integer(body.quantity, 0, 100, 'Số lượng');
      await db.transaction(async connection => {
        if (!quantity) { await connection.run('DELETE FROM cart WHERE user_id=? AND listing_id=?', userId, id); return; }
        const row = await connection.get('SELECT * FROM listings WHERE id=?', id);
        if (!row || row.quantity < quantity) throw new AppError('Tin bán không đủ số lượng.');
        if (row.user_id === userId) throw new AppError('Bạn không thể mua card của chính mình.');
        await connection.run('INSERT INTO cart VALUES(?,?,?) ON CONFLICT(user_id,listing_id) DO UPDATE SET quantity=excluded.quantity', userId, id, quantity);
      });
    },
    async checkout(userId) {
      return db.transaction(async connection => {
        const items = (await connection.all(cartQuery, userId)).map(withCard);
        if (!items.length) throw new AppError('Giỏ hàng đang trống.');
        for (const item of items) if (item.cart_quantity > item.quantity) throw new AppError(`${item.card.name} không còn đủ số lượng. Vui lòng cập nhật giỏ hàng.`, 409);
        const total = items.reduce((sum, item) => sum + item.price * item.cart_quantity, 0);
        integer(total, 1, Number.MAX_SAFE_INTEGER, 'Tổng tiền');
        const { id } = await connection.get('INSERT INTO orders(user_id,total,created) VALUES(?,?,?) RETURNING id', userId, total, new Date().toISOString());
        for (const item of items) {
          await connection.run('UPDATE listings SET quantity=quantity-? WHERE id=?', item.cart_quantity, item.id);
          await connection.run('INSERT INTO order_items(order_id,seller_id,card_id,quantity,price) VALUES(?,?,?,?,?)', id, item.user_id, item.card_id, item.cart_quantity, item.price);
          await addOwned(connection, userId, item.card_id, item.cart_quantity);
        }
        await connection.run('DELETE FROM cart WHERE user_id=?', userId);
        return { id, total };
      });
    },
    async orders(userId) {
      const purchases = await db.all('SELECT * FROM orders WHERE user_id=? ORDER BY id DESC', userId);
      for (const order of purchases) order.items = (await db.all('SELECT * FROM order_items WHERE order_id=? ORDER BY id', order.id)).map(withCard);
      const sales = (await db.all('SELECT order_items.*,orders.created FROM order_items JOIN orders ON orders.id=order_items.order_id WHERE seller_id=? ORDER BY order_id DESC', userId)).map(withCard);
      return { purchases, sales };
    }
  };
}
